rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
fields = list(rows[0].keys())
hit = 0
for r in rows:
    if r.get("学院") != "动物科学技术学院、动物医学院":
        continue
    name = r.get("课程名称","")
    # 跳过解析乱码行（含英文串/数字混排的选修目录）
    if any(ch.isascii() and ch.isalpha() for ch in name):
        continue
    for kw, book, author, ed, pub, isbn in MAP:
        if kw in name and "实验" not in name or (kw in name and "实验" in name and kw=="动物解剖学"):
            # 实验课不配理论教材，跳过
            if "实验" in name and "综合实验" not in book:
                continue
            r["教材名称"]=book; r["主编"]=author; r["版次"]=ed; r["出版社"]=pub
            if isbn: r["ISBN"]=isbn
            r["匹配状态"]="动科动医学院-已配统编教材"
            hit += 1
            break

with io.open(SRC, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
    w.writeheader(); w.writerows(rows)
print("动科动医学院核心课已配教材条数:", hit)
