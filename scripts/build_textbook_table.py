def match(text):
    for kw, book, author, ed, pub, isbn in COMMON:
        if kw in text:
            return (book, author, ed, pub, isbn, "公共课已匹配")
    return ("", "", "", "", "", "待查教学大纲（专业课）")

rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
out_rows = []
filled = 0
for r in rows:
    t = r.get("课程名称","")
    book, author, ed, pub, isbn, status = match(t)
    if book: filled += 1
    out_rows.append({
        "学院": r.get("学院",""), "专业": r.get("专业",""), "学期": r.get("学期",""),
        "课程代码": r.get("课程代码",""), "课程名称": t, "学分": r.get("学分",""),
        "课程性质": r.get("备注",""),
        "教材名称": book, "主编": author, "版次": ed, "出版社": pub, "ISBN": isbn, "匹配状态": status,
    })

fields = ["学院","专业","学期","课程代码","课程名称","学分","课程性质","教材名称","主编","版次","出版社","ISBN","匹配状态"]
with io.open(OUT, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields)
    w.writeheader(); w.writerows(out_rows)
print(f"总课程 {len(out_rows)} 条；公共课已自动匹配教材 {filled} 条；专业课待查大纲 {len(out_rows)-filled} 条")
