rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
fields = list(rows[0].keys())
hit = 0
for r in rows:
    if r.get("学院") != "植物科学技术学院": continue
    name = r.get("课程名称","")
    if any(ch.isascii() and ch.isalpha() for ch in name): continue
    if "实验" in name or "实习" in name or "实践" in name: continue
    for kw, book, author, ed, pub, isbn in MAP:
        if kw in name:
            r["教材名称"]=book; r["主编"]=author; r["版次"]=ed; r["出版社"]=pub
            if isbn: r["ISBN"]=isbn
            r["匹配状态"]="植物科学技术学院-已配统编教材"
            hit += 1; break

with io.open(SRC, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
    w.writeheader(); w.writerows(rows)
print("植物科学技术学院核心课已配教材条数:", hit)
